package fundamentos.dia040;

public class Main {
    static void main(String[] args) {

        int[] numeros = {10, 20, 30, 40, 50};

        System.out.println("==== ELEMENTOS DO ARRAY ====");

        System.out.println("");

        for (int i = 0; i < numeros.length; i++) {
            System.out.println(numeros[i]);
        };

        System.out.println("");

        System.out.println("===============================");
    }
}
